export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem("aquax-language") === "hi" ? "hi" : "en"; }
    catch { return "en"; }
  });

  useEffect(() => {
    try { localStorage.setItem("aquax-language", language); }
    catch { /* Storage may be unavailable; the in-memory preference still works. */ }
  }, [language]);

  const t = (value) => language === "hi" ? hindi[value] || value : value;
  const toggleLanguage = () => setLanguage((current) => current === "en" ? "hi" : "en");

  return <LanguageContext.Provider value={{ language, toggleLanguage, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
